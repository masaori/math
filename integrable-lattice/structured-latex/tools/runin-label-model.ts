/**
 * 検査 L（見出し代わりの断片）の型と判定。
 *
 * ## なぜこの検査が要るのか
 *
 * cycle 27 step 4b は、ユーザーの判断にしたがって本文から強調指定 2534 個を落とした。
 * そのとき強調が唯一の区切りだった箇所が、区切りを失った。
 *
 * 実例（cycle 28 step 3 で全数を読んで見つけた）: 命題 Q の「可算と非可算の分別」と、
 * 7 命題の「限界」。どれも直後の箇条書きを導く見出しとして書かれていたが、
 * 強調を落とすと述語のない体言止めの段落が本文に落ちているだけになる。
 * 読者には、前の段落の続きなのか次の箇条書きの一部なのか分からない。
 *
 * ## 何を見るか
 *
 * 短くて文になっていない段落を違反とする。判定は 2 つの積である。
 *
 * 1. 段落の文字数が短いこと（`MAX_LENGTH`）。長い段落は文になっているとみなす。
 * 2. 文末が句点・コロン等で終わっていないこと。終わっていれば文として読める。
 *
 * ただし段落の直後が別行立て数式のときだけは、この 2 つに加えて
 * 「体言だけの断片」の形（`isNounOnlyFragment`）も要求する。数式へ続く言い回しが
 * 上の 2 つを満たしてしまうためで、理由と実測は下記。
 *
 * ## 判定 1 を除外の形にした理由（cycle 29 step 5。それまでは箇条書きの直前だけを見ていた）
 *
 * cycle 28 step 3 は判定 1 を「直後が箇条書きであること」に限っており、
 * 「走査では他の形は 0 件だったが、0 件だったことと拾えることは別である」を限界に挙げていた。
 * cycle 29 step 5 で本文の実データを走査し、次を実測した（日英あわせて段落 970 件）。
 *
 * - 段落の直後に実際に現れる種別は 4 つだけである。
 *   別行立て数式 257・段落 551・ブロック末尾 108・箇条書き 54。
 * - 入力言語のノード語彙（システム側 `domain-model/structured-text/node.ts`）は閉じており、
 *   表・引用にあたる種別はそもそも存在しない。「表の直前」「引用の直前」は
 *   0 件なのではなく書けない。
 * - 短くて文になっていない段落（46 文字以下・文末が句読点でない）は 67 件あり、
 *   その全件が別行立て数式の直前だった。段落の直前・ブロック末尾には 1 件も無い。
 *
 * そこで判定 1 を許可リスト（箇条書きだけ）から除外リストへ反転させた。
 * 段落の直前・ブロック末尾・箇条書きの直前のいずれでも拾う。将来ノード種別が増えても
 * 既定で拾う側に入る。
 *
 * ## 別行立て数式の直前で、単独の規則がすべて反例を持つこと（cycle 29 step 5 の実測）
 *
 * 数式へ続く言い回しは日本語として正しく、見出しではない。この論文の文体では
 * その言い回しが上の 67 件を占める。単独の規則はいずれも本文に反例を持つ。
 *
 * - 「体言止め（漢字で終わる）なら見出し」…… 反例 2 件。
 *   「(0) 出発点。 の証明の (0) と同じ総和公式」「の (K4) の一意分解」はどちらも数式へ続く。
 * - 「ラテン文字で終わるなら見出し」…… 反例 8 件。
 *   「が成り立ち、したがって命題 V」「where」「and therefore」など。
 * - 「数式を含まないなら見出し」…… 反例 14 件。「すなわち」「したがって」「と」など。
 * - 「閉じ括弧で終わるなら見出し」…… 反例 1 件。「(U1 付値側と位置側の分業)」は
 *   小主張に名前を付けて数式へ渡す、この論文の書き方である。
 *
 * cycle 29 step 5 はここで止め、別行立て数式の直前を丸ごと対象外にした。
 *
 * ## 「体言だけの断片」に限れば切り分けられる（cycle 30 step 4 の実測）
 *
 * 上の 4 つは単独では反例を持つが、積を取ると本文から反例が消える。
 * 判定は次の 4 条件の積で、`isNounOnlyFragment` がこれを実装する。
 *
 * 1. 数式ノードを含まない。見出しに数式は入らない。
 * 2. 相互参照・文献引用を含まない。他のブロックを指す語は、指す先を持つ文の一部である。
 * 3. 途中に句点・ピリオドを含まない。含めばそこで文が切れており、断片ではない。
 * 4. 日本語なら体言（漢字・カタカナ）で終わる。英語なら大文字で始まる。
 *    助詞・活用語尾で終わる語、および小文字で始まる語は、前後の文の一部である。
 *
 * さらに 5 つ目として、数式をまたいで文が続いていないことを見る。
 * 「集合」＋数式＋「を考える。」のように、数式を目的語にして文が数式の向こう側へ
 * 続く書き方があるためで、この形は断片ではなく 1 つの文である。
 * 数式の次の段落が格助詞（を・が・は・に・へ・で・と・の・から・より）で始まるか、
 * 英語で小文字で始まるときは、続いているとみなして違反にしない。
 *
 * ### どの条件が何の反例から来たか（後から緩めないために残す）
 *
 * 条件 1・3・4 は見出しの形そのものの記述だが、条件 2 と 5 は反例から来ている。
 *
 * - 条件 2 は、本文の 2 件（上記の「体言止め」の反例）が相互参照を含むことから入れた。
 * - 条件 5 は、`exact-solution-of-2d-ising-model` の本文とノートから来ている。
 *   同じ入力言語・同じ書き手の別の文書を反例探しの独立な資料として使い、
 *   「集合」＋数式＋「を考える。」と「群の列と群準同型の列」＋数式＋「が完全列であるとは」
 *   の 2 件が条件 1–4 を満たしてしまうことを実測した。
 *
 * ### 発火の実測（2026-08-04）
 *
 * - 本プロジェクトの本文（日英 970 段落、うち数式の直前 257・短い断片 67）: 発火 0 件。
 * - `exact-solution-of-2d-ising-model`（本文とノート 2682 段落、うち数式の直前 1406・
 *   短い断片 921）: 発火 1 件で、それは「積」（直後の数式が積の定義そのもの）である。
 *   これは見出し代わりの断片の形をしており、誤検出ではない。
 *
 * ## 何を見ないか（範囲を正直に書く）
 *
 * - 別行立て数式の直前は、体言だけの断片の形に限って見る。数式へ続く言い回しの形をした
 *   見出し（「限界は」のように助詞で終わるもの等）はここでは拾えない。
 * - 上の 1 件と並んでいる「和（成分ごと）」は、同じ意図で置かれた同じ形でありながら、
 *   閉じ括弧で終わるため条件 4 を満たさず拾えない。判定は形であって意図ではない。
 * - 「文になっているか」を機械で判定してはいない。見ているのは長さと文末の字だけである。
 *   体言止めでも長ければ通るし、短くても句点があれば通る。
 * - 箇条書きの項目の中は見ない。走査するのは `statement` と `proof` の直下の段落だけである。
 * - この検査が捕まえるのは「見出しの代わりに置かれた短い断片」という形だけであって、
 *   読みやすさそのものではない。
 */

export type RunInLabelSite = {
  readonly locale: string;
  readonly blockId: string;
  readonly file: string;
  readonly where: "statement" | "proof";
  /** 段落を平たくした文字列（数式は 1 文字として数える）。 */
  readonly text: string;
  /** 直後のノードの種別。ブロックの最後の段落なら `END_OF_BLOCK`。 */
  readonly nextType: string;
  /** 段落が数式ノードを含むか。 */
  readonly containsMath: boolean;
  /** 段落が相互参照・文献引用を含むか。 */
  readonly containsReference: boolean;
  /**
   * 直後が別行立て数式のとき、その数式のさらに次の段落の字面。
   * 数式の次が段落でなければ `undefined`。文が数式をまたいで続いていないかを見るために使う。
   */
  readonly textAfterDisplay?: string;
};

/** ブロックの最後の段落であることを表す、直後の種別の代わりの印。 */
export const END_OF_BLOCK = "(末尾)";

/** これより長い段落は文になっているとみなす。実測: 直った 8 件はいずれも 12 文字以下だった。 */
export const MAX_LENGTH = 46;

/**
 * 直後がこの種別のときは、長さと文末だけでは判定せず「体言だけの断片」の形も要求する
 * （doc の「体言だけの断片に限れば切り分けられる」）。
 */
export const RESTRICTED_NEXT_TYPES: readonly string[] = ["displayMath"];

/** 文末として認める字。ここで終わっていれば文として読める。 */
const SENTENCE_ENDINGS = ["。", "：", ":", ".", "?", "!", "？", "！"];

/** 体言（漢字・カタカナ）で終わるか。日本語の断片が名詞で閉じていることの判定。 */
const ENDS_WITH_NOUN = /[一-鿿々〆ヵヶ゠-ヿー]$/;

/** 数式の向こう側へ文が続いていることを示す、日本語の書き出し。 */
const CONTINUES_IN_JAPANESE = /^(を|が|は|に|へ|で|と|の|から|より)/;

/**
 * 数式へ続く言い回しではなく、体言だけの断片であるか。
 * 4 条件の積に、数式をまたいで文が続いていないことを加えたもの。
 * 各条件の理由と、どれがどの反例から来たかはファイル冒頭の doc を正本とする。
 */
export const isNounOnlyFragment = (site: RunInLabelSite, text: string): boolean => {
  if (site.containsMath) return false;
  if (site.containsReference) return false;
  if (/[。.]/.test(text)) return false;
  const japanese = site.locale !== "en";
  if (japanese ? !ENDS_WITH_NOUN.test(text) : !/^[A-Z]/.test(text)) return false;
  const after = site.textAfterDisplay;
  if (after !== undefined && (japanese ? CONTINUES_IN_JAPANESE.test(after) : /^[a-z]/.test(after))) {
    return false;
  }
  return true;
};

export const isRunInLabel = (site: RunInLabelSite): boolean => {
  const text = site.text.trim();
  if (text.length === 0 || text.length > MAX_LENGTH) return false;
  if (SENTENCE_ENDINGS.some((ending) => text.endsWith(ending))) return false;
  if (RESTRICTED_NEXT_TYPES.includes(site.nextType)) return isNounOnlyFragment(site, text);
  return true;
};
