/**
 * 検査 L（見出し代わりの断片）の型と判定。
 *
 * ## なぜこの検査が要るのか
 *
 * cycle 27 step 4b は、ユーザーの判断にしたがって本文から強調指定 2534 個を落とした。
 * そのとき強調が唯一の区切りだった箇所が、区切りを失った。
 *
 * 実例（cycle 28 step 3 で全数を読んで見つけた）: 命題 Q の「可算と非可算の分別」と、
 * 7 命題の「限界」。どれも直後の箇条書きを導く見出しとして書かれていたが、
 * 強調を落とすと述語のない体言止めの段落が本文に落ちているだけになる。
 * 読者には、前の段落の続きなのか次の箇条書きの一部なのか分からない。
 *
 * ## 何を見るか
 *
 * 短くて文になっていない段落を違反とする。判定は 3 つの積である。
 *
 * 1. 段落の直後が別行立て数式ではないこと（`EXCLUDED_NEXT_TYPES`。理由は下記）。
 * 2. 段落の文字数が短いこと（`MAX_LENGTH`）。長い段落は文になっているとみなす。
 * 3. 文末が句点・コロン等で終わっていないこと。終わっていれば文として読める。
 *
 * ## 判定 1 を除外の形にした理由（cycle 29 step 5。それまでは箇条書きの直前だけを見ていた）
 *
 * cycle 28 step 3 は判定 1 を「直後が箇条書きであること」に限っており、
 * 「走査では他の形は 0 件だったが、0 件だったことと拾えることは別である」を限界に挙げていた。
 * cycle 29 step 5 で本文の実データを走査し、次を実測した（日英あわせて段落 970 件）。
 *
 * - 段落の直後に実際に現れる種別は 4 つだけである。
 *   別行立て数式 257・段落 551・ブロック末尾 108・箇条書き 54。
 * - 入力言語のノード語彙（システム側 `domain-model/structured-text/node.ts`）は閉じており、
 *   表・引用にあたる種別はそもそも存在しない。「表の直前」「引用の直前」は
 *   0 件なのではなく書けない。
 * - 短くて文になっていない段落（46 文字以下・文末が句読点でない）は 67 件あり、
 *   その全件が別行立て数式の直前だった。段落の直前・ブロック末尾には 1 件も無い。
 *
 * そこで判定 1 を許可リスト（箇条書きだけ）から除外リストへ反転させた。
 * 段落の直前・ブロック末尾・箇条書きの直前のいずれでも拾う。将来ノード種別が増えても
 * 既定で拾う側に入る。
 *
 * ## 別行立て数式の直前だけを除外する理由（実測にもとづく）
 *
 * 数式へ続く言い回しは日本語として正しく、見出しではない。この論文の文体では
 * その言い回しが上の 67 件を占めており、見出しと形で区別できない。
 * 切り分けの規則として考えられるものを実データに当てて、いずれも反例が出ることを確かめた。
 *
 * - 「体言止め（漢字で終わる）なら見出し」…… 反例 2 件。
 *   「(0) 出発点。 の証明の (0) と同じ総和公式」「の (K4) の一意分解」はどちらも数式へ続く。
 * - 「ラテン文字で終わるなら見出し」…… 反例 8 件。
 *   「が成り立ち、したがって命題 V」「where」「and therefore」など。
 * - 「数式を含まないなら見出し」…… 反例 14 件。「すなわち」「したがって」「と」など。
 * - 「閉じ括弧で終わるなら見出し」…… 反例 1 件。「(U1 付値側と位置側の分業)」は
 *   小主張に名前を付けて数式へ渡す、この論文の書き方である。
 *
 * したがって別行立て数式の直前は、形だけでは切り分けられない。
 * ここは検査の対象外とし、その理由を実測値で残す。
 *
 * ## 何を見ないか（範囲を正直に書く）
 *
 * - 別行立て数式の直前は見ない（上記）。ここに見出し代わりの断片を置いても検査は静かなままである。
 * - 「文になっているか」を機械で判定してはいない。見ているのは長さと文末の字だけである。
 *   体言止めでも長ければ通るし、短くても句点があれば通る。
 * - 箇条書きの項目の中は見ない。走査するのは `statement` と `proof` の直下の段落だけである。
 * - この検査が捕まえるのは「見出しの代わりに置かれた短い断片」という形だけであって、
 *   読みやすさそのものではない。
 */

export type RunInLabelSite = {
  readonly locale: string;
  readonly blockId: string;
  readonly file: string;
  readonly where: "statement" | "proof";
  /** 段落を平たくした文字列（数式は 1 文字として数える）。 */
  readonly text: string;
  /** 直後のノードの種別。ブロックの最後の段落なら `END_OF_BLOCK`。 */
  readonly nextType: string;
};

/** ブロックの最後の段落であることを表す、直後の種別の代わりの印。 */
export const END_OF_BLOCK = "(末尾)";

/** これより長い段落は文になっているとみなす。実測: 直った 8 件はいずれも 12 文字以下だった。 */
export const MAX_LENGTH = 46;

/**
 * 直後がこの種別のときは判定しない。形だけでは見出しと数式への言い回しを切り分けられない
 * ことを実データで確かめてある（doc の「別行立て数式の直前だけを除外する理由」）。
 */
export const EXCLUDED_NEXT_TYPES: readonly string[] = ["displayMath"];

/** 文末として認める字。ここで終わっていれば文として読める。 */
const SENTENCE_ENDINGS = ["。", "：", ":", ".", "?", "!", "？", "！"];

export const isRunInLabel = (site: RunInLabelSite): boolean => {
  if (EXCLUDED_NEXT_TYPES.includes(site.nextType)) return false;
  const text = site.text.trim();
  if (text.length === 0 || text.length > MAX_LENGTH) return false;
  return !SENTENCE_ENDINGS.some((ending) => text.endsWith(ending));
};
