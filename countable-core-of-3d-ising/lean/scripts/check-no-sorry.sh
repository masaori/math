  echo "NG: 依存公理の確認に失敗した" >&2
  printf '%s\n' "$output" >&2
  rm -f "$check_file"
  exit 1
}
rm -f "$check_file"

printf '%s\n' "$output"
if printf '%s\n' "$output" | grep -q 'sorryAx'; then
  echo "NG: sorryAx への依存がある" >&2
  status=1
else
  echo "OK: 登録された ${#targets[@]} 件はいずれも sorryAx に依存していない"
fi

exit "$status"
